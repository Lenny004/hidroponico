import { readFileSync, writeFileSync } from "node:fs";

const [, , modo, archivo] = process.argv;
if (!modo || !archivo) {
  process.exit(0);
}

const contenido = readFileSync(archivo, "utf8");
const patron = /Co-authored-by:.*(?:Cursor|cursoragent@cursor\.com)|Made with Cursor|Generated by Cursor/i;

if (modo === "check") {
  if (patron.test(contenido)) {
    console.error("Error: el mensaje no puede incluir coautoría de Cursor o IA.");
    process.exit(1);
  }
  process.exit(0);
}

if (modo === "strip") {
  const limpio = contenido
    .split(/\r?\n/)
    .filter((linea) => !patron.test(linea))
    .join("\n");
  writeFileSync(archivo, limpio, "utf8");
}
