#!/usr/bin/env node
/**
 * Quita o rechaza trailers de coautor de Cursor/IA en mensajes de commit.
 * Uso: node scripts/quitar-coautor-cursor.mjs <strip|check> <archivo-mensaje>
 */
import fs from "node:fs";

const mode = process.argv[2];
const file = process.argv[3];

const prohibido = [
  /^\s*Co-authored-by:.*cursor/i,
  /cursoragent@cursor\.com/i,
  /Made with Cursor/i,
  /Generated by Cursor/i,
];

function lineaProhibida(line) {
  return prohibido.some((re) => re.test(line));
}

if (!file || !fs.existsSync(file)) {
  process.exit(0);
}

const raw = fs.readFileSync(file, "utf8");
const nl = raw.includes("\r\n") ? "\r\n" : "\n";
const lines = raw.split(/\r?\n/);

if (mode === "check") {
  const mala = lines.find(lineaProhibida);
  if (mala) {
    console.error(
      "Error: este repositorio no permite Co-authored-by de Cursor ni trailers de IA.",
    );
    console.error(`Línea rechazada: ${mala.trim()}`);
    process.exit(1);
  }
  process.exit(0);
}

fs.writeFileSync(file, lines.filter((line) => !lineaProhibida(line)).join(nl));
